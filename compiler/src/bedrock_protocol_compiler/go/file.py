import re
import subprocess

from bedrock_protocol_compiler.descriptor import CompilerError
from bedrock_protocol_compiler.go import names
from bedrock_protocol_compiler.printer import Printer
from bedrock_protocol_compiler.schema import Schema

STRING_LITERAL = re.compile(r'"(?:[^"\\]|\\.)*"')
HEADER = "// Code generated by bpc. DO NOT EDIT."


def write(schema: Schema, out: Printer, path: str, body: Printer) -> None:
    text = STRING_LITERAL.sub('""', body.text)
    found = sorted(
        spelled for name, spelled in names.imports(schema).items() if re.search(rf"(?<![\w.]){name}\.", text)
    )
    source = Printer()
    source.emit(HEADER)
    source.emit("")
    source.emit("package $package$", package=names.package(schema))
    source.emit("")
    if found:
        source.emit("import (")
        with source.indent():
            standard = [spelled for spelled in found if "." not in spelled.partition("/")[0]]
            groups = [group for group in (standard, sorted(set(found) - set(standard))) if group]
            for index, group in enumerate(groups):
                if index:
                    source.emit("")
                for spelled in group:
                    source.emit('"$spelled$"', spelled=spelled)
        source.emit(")")
        source.emit("")
    source.lines.extend(body.lines)
    try:
        formatted = subprocess.run(["gofmt"], input=source.text, capture_output=True, text=True, check=False)
    except FileNotFoundError as error:
        raise CompilerError("gofmt: is not on the PATH") from error
    if formatted.returncode != 0:
        raise CompilerError(f"{path}: gofmt rejects it: {formatted.stderr.strip()}")
    out.lines.extend(formatted.stdout.removesuffix("\n").split("\n"))
