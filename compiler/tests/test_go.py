import pytest

from bedrock_protocol_compiler.__main__ import main

HEADER = """
import uuid
from enum import IntEnum
from typing import Literal
from protocol import (
    array, bitset, builtin, double, field, int16, int32, packet, sentinel, type, uint8, uint16, uint32, uvarint32,
    uvarint64, value,
)
package = "bedrock.protocol"
java_package = "dev.endstone.protocol"
go_package = "github.com/EndstoneMC/bedrock-protocol/go/protocol"
"""

SCALAR = """
@packet(id=7)
class P:
    x: uint8
"""

COLORS = """
class Color(IntEnum, uint8):
    RED = 1
    CRIMSON = RED
    BLUE = value(2, deprecated=True)
"""

GROWING = (
    "class Mode(IntEnum, uint8):\n    A = 0\n    B = value(1, since=3)\n    C = value(2, since=5)\n\n"
    "@packet(id=7)\nclass P:\n    m: Mode\n"
)

NAMED = (
    "class Kind(IntEnum, uint8):\n    A = 1\n    B = 2\n    LATEST = value(B, default=True)\n\n"
    "@packet(id=7)\nclass P:\n    k: Kind = field(type=str)\n"
)

HAND_WRITTEN = (
    "class S:\n    x: uint8\n\n@type(cereal=False)\nclass S:\n    x: uint16\n\n"
    "@packet(id=1)\nclass P:\n    s: S = field(cereal=False)\n    t: S\n"
)

EXCLUDED = """
class Info:
    id: uint8
    capable: bool

@packet(id=1)
class P:
    behavior: list[Info] = field(exclude="capable")
"""

NESTED = "class P:\n    class N:\n        x: uint8\n    n: N\n"

UNION = "@packet(id=7)\nclass P:\n    u: uint8 | str\n"

OPTIONAL_UNION = "@packet(id=7)\nclass P:\n    u: None | uint8 | str\n"

BUILTIN = "@builtin\nclass NBTThing:\n    pass\n\nclass P:\n    t: NBTThing\n"


@pytest.fixture
def go(build_package, tmp_path):
    def run(source: str):
        build_package({"a": HEADER + source})
        main([str(tmp_path / "protocol"), "--go-out", str(tmp_path / "go")])
        return tmp_path / "go/protocol"

    return run


@pytest.fixture
def emitted(go):
    def read(source: str, path: str = "a.bpc.go") -> str:
        return (go(source) / path).read_text()

    return read


def test_go_out_writes_a_file_per_module(build_package, tmp_path):
    build_package({"a": HEADER + SCALAR, "b": HEADER + "class S:\n    x: uint8\n"})

    main([str(tmp_path / "protocol"), "--go-out", str(tmp_path / "go")])

    assert sorted(path.name for path in (tmp_path / "go/protocol").glob("*.bpc.go")) == [
        "a.bpc.go",
        "b.bpc.go",
        "protocol.bpc.go",
    ]


def test_go_out_writes_the_test_half_of_a_module_beside_it(go):
    assert sorted(path.name for path in go(SCALAR).glob("*.bpc_test.go")) == ["a.bpc_test.go", "protocol.bpc_test.go"]


def test_out_alone_writes_no_go_tree(build_package, tmp_path):
    build_package({"a": HEADER + SCALAR})

    main([str(tmp_path / "protocol"), "--out", str(tmp_path / "out")])

    assert sorted(path.name for path in tmp_path.iterdir()) == ["out", "protocol"]


def test_a_go_error_writes_no_output(build_package, tmp_path):
    build_package({"a": HEADER + "class Packet:\n    x: uint8\n"})

    with pytest.raises(
        SystemExit, match=r"bpc: protocol\.Packet: is generated for both the runtime and the message Packet$"
    ):
        main([str(tmp_path / "protocol"), "--out", str(tmp_path / "out"), "--go-out", str(tmp_path / "go")])

    assert sorted(path.name for path in tmp_path.iterdir()) == ["protocol"]


def test_a_stale_generated_file_is_deleted(build_package, tmp_path):
    build_package({"a": HEADER + SCALAR})
    stale = tmp_path / "go/protocol/old.bpc_test.go"
    stale.parent.mkdir(parents=True)
    stale.write_text("package protocol\n")

    main([str(tmp_path / "protocol"), "--go-out", str(tmp_path / "go")])

    assert not stale.exists()


def test_a_hand_written_file_beside_the_generated_ones_is_kept(build_package, tmp_path):
    build_package({"a": HEADER + SCALAR})
    kept = tmp_path / "go/protocol/protocol.go"
    kept.parent.mkdir(parents=True)
    kept.write_text("package protocol\n")

    main([str(tmp_path / "protocol"), "--go-out", str(tmp_path / "go")])

    assert kept.read_text() == "package protocol\n"


