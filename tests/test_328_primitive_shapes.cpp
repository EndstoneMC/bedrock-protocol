// mce::Color packs ARGB into an int32: A=0x44, R=0x55, G=0x66, B=0x77.
constexpr auto argb = bp::Color{0x44556677};

// The three shapes below are shaped identically at both eras, so each is built once
// against whichever snapshot's payload the caller wants. The type enum gained members
// at 1001 and the text payload a field at 2192, so both are versioned alongside the
// payload and come from it.
template <class Payload>
using ShapeTypeOf = typename decltype(Payload::shape_type)::value_type;

template <class Payload>
using TextPayloadOf = std::variant_alternative_t<2, decltype(Payload::extra_data_payload)>;

// Every optional left empty: the shape is cleared, and the variant sits on its
// std::monostate case.
template <class Payload>
Payload cleared_shape()
{
    Payload shape;
    shape.network_id = 1;
    return shape;
}

template <class Payload>
Payload sphere_shape()
{
    Payload shape;
    shape.network_id = 3;
    shape.shape_type = ShapeTypeOf<Payload>::Sphere;
    shape.location = bp::Vec3{.x = 1.0f, .y = 2.0f, .z = 3.0f};
    shape.scale = 0.5f;
    shape.rotation = bp::Vec3{.x = 0.0f, .y = 0.25f, .z = 0.0f};
    shape.time_left_total_sec = 2.0f;
    shape.max_render_distance = 64.0f;
    shape.color = argb;
    shape.dimension_id = bp::DimensionType{1};
    shape.attached_to_id = bp::ActorUniqueID{-7};
    shape.extra_data_payload = bp::SphereDataPayload{.num_segments = 12};
    return shape;
}

template <class Payload>
Payload text_shape()
{
    Payload shape;
    shape.network_id = 4;
    shape.shape_type = ShapeTypeOf<Payload>::Text;
    shape.extra_data_payload = TextPayloadOf<Payload>{
        .text = "hi",
        .use_rotation = true,
        .background_color = argb,
        .depth_test = true,
        .show_backface = false,
        .show_text_backface = true,
    };
    return shape;
}

