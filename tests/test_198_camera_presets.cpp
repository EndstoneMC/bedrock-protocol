template <class Packet>
Packet two_presets()
{
    using Preset = typename decltype(Packet::camera_presets.presets)::value_type;

    Preset bare;
    bare.name = "bare";

    Preset loaded;
    loaded.name = "loaded";
    loaded.inherit_from = "minecraft:free";
    loaded.pos_x = 1.0f;
    loaded.pos_y = 2.0f;
    loaded.pos_z = 3.0f;
    loaded.rot_x = 0.5f;
    loaded.rot_y = 0.25f;
    loaded.camera_rotation_speed = 4.0f;
    loaded.snap_to_target = true;
    loaded.horizontal_rotation_limit = bp::Vec2{.x = 1.0f, .y = 2.0f};
    loaded.vertical_rotation_limit = bp::Vec2{.x = 3.0f, .y = 4.0f};
    loaded.continue_targeting = false;
    loaded.tracking_radius = 8.0f;
    loaded.view_offset = bp::Vec2{.x = 5.0f, .y = 6.0f};
    loaded.entity_offset = bp::Vec3{.x = 7.0f, .y = 8.0f, .z = 9.0f};
    loaded.radius = 16.0f;
    loaded.yaw_limit_min = -90.0f;
    loaded.yaw_limit_max = 90.0f;
    loaded.listener = Preset::AudioListener::PLAYER;
    loaded.player_effects = true;
    loaded.control_scheme = bp::Scheme::CAMERA_RELATIVE_STRAFE;

    Packet packet;
    packet.camera_presets.presets = {bare, loaded};
    return packet;
}

