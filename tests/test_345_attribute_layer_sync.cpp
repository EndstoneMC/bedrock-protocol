// A case-2 (UpdateEnvironmentAttributes) packet carrying one bool attribute.
// The only version-varying part is EnvironmentAttributeData, which gains
// local_transition_ticks + noise_transition at the 976 step.
template <int V>
bp::ClientboundAttributeLayerSyncPacket_<V> make_packet()
{
    bp::EnvironmentAttributeData_<V> env;
    env.name = "temp";
    env.attribute = bp::BoolAttributeData{true, bp::BoolAttributeOperation::Override};
    env.current_transition_ticks = 0;
    env.total_transition_ticks = 0;
    env.easing = bp::EasingType::Linear;
    if constexpr (V == 1001) {
        env.local_transition_ticks = 0;
        env.noise_transition = false;
    }

    bp::UpdateEnvironmentAttributesData_<V> inner;
    inner.layer_name = "wet";
    inner.layer_dimension_id = bp::DimensionType{0};
    inner.attributes = {env};

    bp::ClientboundAttributeLayerSyncPacket_<V> packet;
    packet.data = inner;
    return packet;
}

// generated by gophertunnel (v1.57.1):
// packet.ClientBoundAttributeLayerSync{PayloadType: UpdateEnvironment, LayerName: "wet",
//   DimensionID: 0, EnvironmentAttributes: []protocol.EnvironmentAttributeData{{
//   AttributeName: "temp", Attribute: {Type: Bool, BoolValue: true,
//   BoolOperation: Option[int32](Override)}}}}
// One patch: gophertunnel writes the operation as an optional int32, which is wrong.
// BoolEnvironmentAttribute::mOperation is a cereal-bound enum, so it reaches the wire
// name-coded, as EAS::BoolAttributeData dumps it. BDS binds OVERRIDE and cereal folds it,
// so the wire carries "override"; the easing name is the same patch, and BDS already
// spells EasingType snake_case, so LINEAR folds straight onto its "linear".
