@pytest.mark.parametrize("version", [v975, v1001, v2168])
def test_crafting_data_is_packet_52(version):
    assert version.PACKETS[52] is version.CraftingDataPacket


@pytest.mark.parametrize(("packet", "golden"), GOLDENS)
def test_crafting_data_encodes_to_its_golden(packet, golden):
    assert bytes(packet) == golden


@pytest.mark.parametrize(("packet", "golden"), GOLDENS)
def test_crafting_data_decodes_from_its_golden(packet, golden):
    assert type(packet).from_bytes(golden) == packet


def test_crafting_data_1001_empty_body_is_rejected_at_2168():
    with pytest.raises(ValueError, match="at byte"):
        v2168.CraftingDataPacket.from_bytes(EMPTY_V1001)


def test_crafting_data_2168_empty_body_leaves_trailing_bytes_at_1001():
    with pytest.raises(ValueError, match="trailing bytes"):
        v1001.CraftingDataPacket.from_bytes(EMPTY_V2168)
