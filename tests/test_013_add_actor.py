GOLDENS = [
    pytest.param(
        v1001.AddActorPacket(
            **COMMON,
            data=v1001.SynchedActorData.CopyableDataList(
                data=[v1001.DataItemEntry(id=38, payload=v1001.DataItemFloatPayload(value=0.5))]
            ),
        ),
        V1001,
        id="v1001",
    ),
    pytest.param(
        v2168.AddActorPacket(
            **COMMON,
            data=v2168.SynchedActorData.CopyableDataList(
                data=[v2168.DataItemEntry(id=38, payload=v2168.DataItemFloatPayload(value=0.5))]
            ),
        ),
        V2168,
        id="v2168",
    ),
]

PASSENGER_BLOCK_DATA = v2225.PassengerOfBlockArguments(
    block_pos=v2225.BlockPos(x=1, y=2, z=3),
    offset=v2225.Vec3(x=0.0, y=0.5, z=0.0),
    rotation=90.0,
    rotation_limit=45.0,
    emote=v2225.PassengerOfBlockArguments.EmoteType.LAYING,
)


@pytest.mark.parametrize("version", [v1001, v2168])
def test_add_actor_is_packet_13(version):
    assert version.packets[13] is version.AddActorPacket


@pytest.mark.parametrize(("packet", "golden"), GOLDENS)
def test_add_actor_encodes_to_its_golden(packet, golden):
    assert bytes(packet) == golden


@pytest.mark.parametrize(("packet", "golden"), GOLDENS)
def test_add_actor_decodes_from_its_golden(packet, golden):
    assert type(packet).from_bytes(golden) == packet


def test_2168_adds_one_type_byte_per_data_item():
    assert V2168[:89] + V2168[90:] == V1001
    assert V2168[89:90] == bytes.fromhex("03")


def test_a_2168_body_is_rejected_at_1001():
    with pytest.raises(ValueError, match="at byte"):
        v1001.AddActorPacket.from_bytes(V2168)


def test_an_empty_data_list_encodes_identically_at_1001_and_2168():
    assert bytes(v1001.AddActorPacket(**COMMON)) == bytes(v2168.AddActorPacket(**COMMON))


def test_2225_appends_the_passenger_block_data_after_the_2193_body():
    assert bytes(v2225.AddActorPacket(**COMMON))[:-1] == bytes(v2193.AddActorPacket(**COMMON))


def test_2225_adds_one_byte_for_an_absent_passenger_block_data():
    assert len(bytes(v2225.AddActorPacket(**COMMON))) == len(bytes(v2193.AddActorPacket(**COMMON))) + 1


def test_2225_passenger_block_data_adds_24_bytes():
    absent = bytes(v2225.AddActorPacket(**COMMON))
    present = bytes(v2225.AddActorPacket(**COMMON, passenger_of_block_data=PASSENGER_BLOCK_DATA))
    assert len(present) == len(absent) + 24


def test_2225_passenger_block_data_round_trips():
    packet = v2225.AddActorPacket(**COMMON, passenger_of_block_data=PASSENGER_BLOCK_DATA)
    assert v2225.AddActorPacket.from_bytes(bytes(packet)) == packet
